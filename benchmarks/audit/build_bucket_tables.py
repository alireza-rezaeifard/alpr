"""Build per-width-bucket tables (task S8) and per-bucket comparison (S11).

Reads benchmarks/results/phase2b_detector_crop_results.json (records only).
The video benchmark is NOT re-run. Bucket boundaries come unchanged from
benchmarks/ab_helpers.bucket_for().
"""
from __future__ import annotations

import json
import os
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "benchmarks"))

from ab_helpers import BUCKETS, bucket_for  # noqa: E402

RESULTS = os.path.join(ROOT, "benchmarks", "results",
                       "phase2b_detector_crop_results.json")
OUT = os.path.join(HERE, "bucket_tables.md")
DETECTORS = ["current_detector", "iranplate_vision"]


def med(vals):
    return statistics.median(vals) if vals else None


def fmt_rate(num, den):
    if not den:
        return "n/a"
    return f"{num / den:.3f} ({num}/{den})"


def fmt_med(v):
    return "n/a" if v is None else f"{v:.1f}"


def gt_na():
    return "*Ground Truth unavailable - accuracy not measurable*"


def main():
    with open(RESULTS, "r", encoding="utf-8") as fh:
        records = json.load(fh)["records"]

    print("record keys:", sorted(records[0].keys()))
    dets = sorted({r["detector"] for r in records})
    print("detectors present:", dets)
    print("cameras present:", sorted({r["camera"] for r in records}))
    resolved = {}
    for want in DETECTORS:
        match = [d for d in dets if want.split("_")[0] in d]
        resolved[want] = match[0] if match else None
    print("detector key resolution:", resolved)

    bucket_names = [name for _, _, name in BUCKETS]
    lines = []
    w = lines.append

    w("# Crop-width bucket tables (Phase 2B)")
    w("")
    w("Generated by `benchmarks/audit/build_bucket_tables.py` from "
      "`benchmarks/results/phase2b_detector_crop_results.json` (`records`, "
      f"{len(records)} rows). Bucket boundaries come unchanged from "
      "`benchmarks/ab_helpers.bucket_for()`: "
      + ", ".join(f"`{lo}-{'inf' if hi > 10 ** 8 else hi}`=`{n}`"
                  for lo, hi, n in BUCKETS) + ".")
    w("")
    w("Accuracy is reported **only** where ground truth exists "
      "(`gt_status == 'LABELED'`); all other rows read "
      "`Ground Truth unavailable - accuracy not measurable`.")
    w("")

    # ---- Table A: spec S8 ----
    w("## Table A - per detector x width bucket (spec S8)")
    w("")
    w("| Detector | Camera | Width bucket | n samples | exact accuracy | "
      "character accuracy | invalid rate | failed rate | median OCR latency "
      "(ms) | median detector latency (ms) | clipping rate |")
    w("| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")

    LABELS = {"current_detector": "Current Detector",
              "iranplate_vision": "IranPlate-Vision"}
    for want in DETECTORS:
        det = resolved[want]
        for cam in sorted({r["camera"] for r in records}):
            for b in bucket_names:
                sel = [r for r in records if r["detector"] == det
                       and r["camera"] == cam
                       and bucket_for(int(r["width"])) == b]
                n = len(sel)
                lab = [r for r in sel if r.get("gt_status") == "LABELED"]
                chars = [r["char_accuracy"] for r in lab
                         if r.get("char_accuracy") is not None]
                invalid = sum(1 for r in sel if not r.get("ocr_valid"))
                failed = sum(1 for r in sel if r.get("failed")
                             or not str(r.get("ocr_text") or "").strip())
                clipped = sum(1 for r in sel if r.get("clipped_any"))
                acc = (f"**{fmt_rate(sum(1 for r in lab if r['exact']), len(lab))}**"
                       if lab else gt_na())
                char = (f"{statistics.mean(chars):.3f}" if chars else gt_na())
                w(f"| {LABELS[want]} | {cam} | {b} px | {n} | {acc} | {char} | "
                  f"{fmt_rate(invalid, n)} | {fmt_rate(failed, n)} | "
                  f"{fmt_med(med([r['ocr_latency_ms'] for r in sel]))} | "
                  f"{fmt_med(med([r['detector_latency_ms'] for r in sel]))} | "
                  f"{fmt_rate(clipped, n)} |")
    w("")

    # ---- Table B: spec S11 repeated per bucket ----
    w("## Table B - comparison repeated for each crop-width bucket (spec S11)")
    w("")
    w("Crops of both cameras pooled per bucket. Accuracy metrics use LABELED "
      "crops only; geometry / latency / invalidity metrics use all crops.")
    w("")
    w("| Bucket | Metric | Current Detector | IranPlate-Vision |")
    w("| --- | --- | ---: | ---: |")

    metrics = [
        ("verified samples", "verified"),
        ("exact accuracy", "exact"),
        ("character accuracy", "char"),
        ("edit distance (mean)", "edit"),
        ("invalid rate", "invalid"),
        ("failed rate", "failed"),
        ("median crop width (px)", "mw"),
        ("median crop height (px)", "mh"),
        ("clipping rate", "clip"),
        ("detector latency p50 (ms)", "det"),
        ("OCR latency p50 (ms)", "ocr"),
        ("total latency p50 (ms)", "tot"),
    ]

    def pool(want, b):
        return [r for r in records if r["detector"] == resolved[want]
                and bucket_for(int(r["width"])) == b]

    def val(want, b, key):
        sel = pool(want, b)
        n = len(sel)
        lab = [r for r in sel if r.get("gt_status") == "LABELED"]
        if key == "verified":
            return str(len(lab))
        if key == "exact":
            e = sum(1 for r in lab if r["exact"])
            return f"{e / len(lab):.3f} ({e}/{len(lab)})" if lab else gt_na()
        if key == "char":
            ch = [r["char_accuracy"] for r in lab
                  if r.get("char_accuracy") is not None]
            return f"{statistics.mean(ch):.3f}" if ch else gt_na()
        if key == "edit":
            ed = [r["edit_distance"] for r in lab
                  if r.get("edit_distance") is not None]
            return f"{statistics.mean(ed):.3f}" if ed else gt_na()
        if key == "invalid":
            return fmt_rate(sum(1 for r in sel if not r.get("ocr_valid")), n)
        if key == "failed":
            return fmt_rate(sum(1 for r in sel if r.get("failed")
                                or not str(r.get("ocr_text") or "").strip()), n)
        if key == "mw":
            return fmt_med(med([r["width"] for r in sel]))
        if key == "mh":
            return fmt_med(med([r["height"] for r in sel]))
        if key == "clip":
            return fmt_rate(sum(1 for r in sel if r.get("clipped_any")), n)
        if key == "det":
            return fmt_med(med([r["detector_latency_ms"] for r in sel]))
        if key == "ocr":
            return fmt_med(med([r["ocr_latency_ms"] for r in sel]))
        if key == "tot":
            return fmt_med(med([r["total_latency_ms"] for r in sel]))
        raise KeyError(key)

    for b in bucket_names:
        first = True
        for label, key in metrics:
            name = f"{b} px" if first else ""
            first = False
            w(f"| {name} | {label} | {val('current_detector', b, key)} | "
              f"{val('iranplate_vision', b, key)} |")
    w("")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
